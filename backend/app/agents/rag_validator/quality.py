from collections import Counter

from app.agents.project_planner.schemas import ProjectPlan
from app.agents.requirement_analyst.schemas import RequirementAnalysis
from app.agents.software_architect.schemas import SystemArchitecture

from .schemas import RAGValidationReport


class RAGValidationQualityController:
    """
    Deterministic validation for RAGValidationReport.
    """

    def validate(
        self,
        report: RAGValidationReport,
        requirements: RequirementAnalysis,
        project_plan: ProjectPlan,
        architecture: SystemArchitecture,
        retrieved_chunk_ids: set[str],
    ) -> RAGValidationReport:

        self._check_project_name(
            report,
            requirements,
        )

        normalized_report = self._normalize_source_ids(
            report,
            retrieved_chunk_ids,
        )

        self._check_knowledge_sources(
            normalized_report,
            retrieved_chunk_ids,
        )

        self._check_findings(
            normalized_report,
            retrieved_chunk_ids,
        )

        self._check_status(
            normalized_report,
        )

        return normalized_report

    @staticmethod
    def _normalize_source_ids(
        report: RAGValidationReport,
        retrieved_chunk_ids: set[str],
    ) -> RAGValidationReport:
        """
        Normalize document-level references returned by the LLM to the
        exact chunk IDs retrieved from the vector store.

        Example:

            architecture_patterns
                ->
            architecture_patterns-0

        Only an unambiguous document-to-chunk mapping is accepted.
        """

        def resolve_id(
            source_id: str,
        ) -> str:

            source_id = source_id.strip()

            if source_id in retrieved_chunk_ids:
                return source_id

            matching_chunks = [
                chunk_id
                for chunk_id in retrieved_chunk_ids
                if chunk_id.startswith(
                    f"{source_id}-"
                )
            ]

            if len(matching_chunks) == 1:
                return matching_chunks[0]

            return source_id

        report.knowledge_sources = [
            resolve_id(source_id)
            for source_id in report.knowledge_sources
        ]

        for finding in report.findings:
            finding.evidence_chunk_ids = [
                resolve_id(chunk_id)
                for chunk_id in finding.evidence_chunk_ids
            ]

        return report

    @staticmethod
    def _check_project_name(
        report: RAGValidationReport,
        requirements: RequirementAnalysis,
    ) -> None:

        if report.project_name.strip().casefold() != (
            requirements.project_name.strip().casefold()
        ):
            raise ValueError(
                "RAG validation project_name does not match "
                "RequirementAnalysis project_name."
            )

    @staticmethod
    def _check_knowledge_sources(
        report: RAGValidationReport,
        retrieved_chunk_ids: set[str],
    ) -> None:

        if not report.knowledge_sources:
            raise ValueError(
                "RAG validation must contain at least one knowledge source."
            )

        unknown_sources = (
            set(report.knowledge_sources)
            - retrieved_chunk_ids
        )

        if unknown_sources:
            raise ValueError(
                "RAG validation references unknown knowledge chunks: "
                f"{sorted(unknown_sources)}"
            )

        # Remove harmless duplicate source references.
        report.knowledge_sources = list(
            dict.fromkeys(
                report.knowledge_sources
            )
        )

    @staticmethod
    def _check_findings(
        report: RAGValidationReport,
        retrieved_chunk_ids: set[str],
    ) -> None:

        # Remove exact duplicate claims generated by the LLM.
        unique_findings = []
        seen_claims = set()

        for finding in report.findings:

            claim = finding.claim.strip().casefold()

            if claim in seen_claims:
                continue

            seen_claims.add(claim)
            unique_findings.append(finding)

        report.findings = unique_findings

        titles = [
            finding.title.strip().casefold()
            for finding in report.findings
        ]

        duplicate_titles = [
            title
            for title, count in Counter(
                titles
            ).items()
            if count > 1
        ]

        if duplicate_titles:
            raise ValueError(
                "Duplicate RAG validation finding titles found: "
                f"{duplicate_titles}"
            )

        for finding in report.findings:

            if not finding.title.strip():
                raise ValueError(
                    "RAG validation finding title cannot be empty."
                )

            if not finding.claim.strip():
                raise ValueError(
                    f"RAG finding '{finding.title}' "
                    "must contain a claim."
                )

            if not finding.evidence.strip():
                raise ValueError(
                    f"RAG finding '{finding.title}' "
                    "must contain evidence."
                )

            if not finding.recommendation.strip():
                raise ValueError(
                    f"RAG finding '{finding.title}' "
                    "must contain a recommendation."
                )

            if not finding.evidence_chunk_ids:
                raise ValueError(
                    f"RAG finding '{finding.title}' "
                    "must cite at least one knowledge chunk."
                )

            unknown_ids = (
                set(finding.evidence_chunk_ids)
                - retrieved_chunk_ids
            )

            if unknown_ids:
                raise ValueError(
                    f"RAG finding '{finding.title}' references unknown "
                    f"knowledge chunks: {sorted(unknown_ids)}"
                )

    @staticmethod
    def _check_status(
        report: RAGValidationReport,
    ) -> None:

        unsupported_findings = any(
            finding.verdict == "UNSUPPORTED"
            for finding in report.findings
        )

        questionable_findings = any(
            finding.verdict == "QUESTIONABLE"
            for finding in report.findings
        )

        if (
            report.overall_status == "PASS"
            and (
                unsupported_findings
                or questionable_findings
            )
        ):
            raise ValueError(
                "RAG validation cannot be PASS when QUESTIONABLE or "
                "UNSUPPORTED findings exist."
            )

        if (
            report.overall_status == "NEEDS_REVIEW"
            and not report.findings
        ):
            raise ValueError(
                "RAG validation is NEEDS_REVIEW but contains no findings."
            )