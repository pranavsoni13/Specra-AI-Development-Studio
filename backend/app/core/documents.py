from __future__ import annotations

import re
from datetime import datetime, timezone
from typing import Any

DOCUMENT_TYPES = {"srs", "sdd", "test-report"}


def _value(value: Any, empty: str = "Not specified in the generated artifact.") -> str:
    if value is None:
        return empty
    if isinstance(value, str):
        return value.strip() or empty
    return str(value)


def _bullets(values: Any, empty: str = "No items were recorded in the source artifact.") -> str:
    if not isinstance(values, list) or not values:
        return "- " + empty
    items = [str(value).strip() for value in values if str(value).strip()]
    return "\n".join("- " + item for item in items) if items else "- " + empty


def _artifact(artifacts: dict, *keys: str) -> dict:
    for key in keys:
        value = artifacts.get(key)
        if isinstance(value, dict):
            return value
    return {}


def _title(project: dict, artifacts: dict) -> str:
    requirements = _artifact(artifacts, "requirements")
    return _value(
        requirements.get("project_name") or project.get("project_name"),
        "Untitled Specra Project",
    )


def _srs(project: dict, artifacts: dict, title: str) -> str:
    req = _artifact(artifacts, "requirements")
    sections = [
        f"# Software Requirements Specification (SRS): {title}",
        "",
        "> Generated by Specra from the saved requirements artifact. Review and approve it before treating it as a contractual specification.",
        "",
        "## Document control",
        "",
        f"- Project ID: {_value(project.get('project_id'))}",
        f"- Project status: {_value(project.get('status'))}",
        f"- Generated (UTC): {datetime.now(timezone.utc).isoformat()}",
        "- Source: current saved Specra requirements artifact",
        "",
        "## 1. Purpose and objective",
        "",
        _value(req.get("objective")),
        "",
        "## 2. Intended user roles",
        "",
        _bullets(req.get("user_roles")),
        "",
        "## 3. Functional requirements",
        "",
    ]
    functional = req.get("functional_requirements")
    sections.extend(
        f"{i}. {value}" for i, value in enumerate(
            functional if isinstance(functional, list) and functional else [
                "No functional requirements were recorded."
            ],
            start=1,
        )
    )
    sections.extend([
        "",
        "## 4. Non-functional requirements",
        "",
        _bullets(req.get("non_functional_requirements"), "No explicit non-functional requirements were recorded."),
        "",
        "## 5. Constraints",
        "",
        _bullets(req.get("constraints"), "No explicit constraints were recorded."),
        "",
        "## 6. Assumptions",
        "",
        _bullets(req.get("assumptions"), "No assumptions were recorded."),
        "",
        "## 7. Risks",
        "",
        _bullets(req.get("risks"), "No risks were recorded."),
        "",
        "## 8. Clarifications required",
        "",
        _bullets(req.get("clarifications_needed"), "No open clarification questions were recorded."),
        "",
        "## 9. Review note",
        "",
        "This document reflects saved AI-generated requirements, not independent stakeholder approval. Resolve open questions and confirm scope before implementation.",
        "",
    ])
    return "\n".join(sections)


def _sdd(project: dict, artifacts: dict, title: str) -> str:
    req = _artifact(artifacts, "requirements")
    plan = _artifact(artifacts, "project_plan")
    arch = _artifact(artifacts, "architecture")
    review = _artifact(artifacts, "technical_review", "review")
    sections = [
        f"# Software Design Description (SDD): {title}",
        "",
        "> Generated by Specra from the saved plan and architecture. Treat undecided choices as proposals until approved by the engineering team.",
        "",
        "## Document control",
        "",
        f"- Project ID: {_value(project.get('project_id'))}",
        f"- Project status: {_value(project.get('status'))}",
        f"- Requirements artifact: {'available' if artifacts.get('requirements') else 'not available'}",
        f"- Project plan artifact: {'available' if artifacts.get('project_plan') else 'not available'}",
        f"- Architecture artifact: {'available' if artifacts.get('architecture') else 'not available'}",
        "",
        "## 1. Design overview",
        "",
        f"Objective: {_value(req.get('objective'))}",
        f"Architecture style: {_value(arch.get('architecture_style'))}",
        "",
        "## 2. Technology and platform choices",
        "",
        f"- Frontend: {_value(arch.get('frontend'))}",
        f"- Backend: {_value(arch.get('backend'))}",
        f"- Database: {_value(arch.get('database'))}",
        f"- Authentication: {_value(arch.get('authentication'))}",
        "",
        "## 3. Components and responsibilities",
        "",
    ]
    components = arch.get("components")
    if isinstance(components, list) and components:
        for item in components:
            if not isinstance(item, dict):
                continue
            refs = ", ".join(str(x) for x in item.get("related_requirements", [])) or "No requirement references supplied"
            sections.extend([
                f"### {_value(item.get('name'), 'Unnamed component')}",
                "",
                _value(item.get("responsibility")),
                "",
                f"- Requirement traceability: {refs}",
                "",
            ])
    else:
        sections.extend(["No architecture components have been generated yet.", ""])
    sections.extend(["## 4. API capabilities", ""])
    endpoints = arch.get("api_endpoints")
    if isinstance(endpoints, list) and endpoints:
        for item in endpoints:
            if isinstance(item, dict):
                refs = ", ".join(str(x) for x in item.get("related_requirements", [])) or "No requirement references supplied"
                sections.append(f"- **{_value(item.get('name'))}** — {_value(item.get('purpose'))} (requirements: {refs})")
    else:
        sections.append("No API capabilities have been generated yet.")
    sections.extend(["", "## 5. Data flow", "", _bullets(arch.get("data_flow")), "", "## 6. Architecture decisions", ""])
    decisions = arch.get("architecture_decisions")
    if isinstance(decisions, list) and decisions:
        for index, item in enumerate(decisions, start=1):
            if not isinstance(item, dict):
                continue
            refs = ", ".join(str(x) for x in item.get("related_requirements", [])) or "No requirement references supplied"
            sections.extend([
                f"### Decision {index}: {_value(item.get('decision'))}",
                "",
                f"Rationale: {_value(item.get('rationale'))}",
                f"Requirement references: {refs}",
                "",
            ])
    else:
        sections.extend(["No architecture decisions were recorded.", ""])
    sections.extend([
        "## 7. External integrations",
        "",
        _bullets(arch.get("external_integrations"), "No external integrations were recorded."),
        "",
        "## 8. Architectural assumptions",
        "",
        _bullets(arch.get("architectural_assumptions"), "No architectural assumptions were recorded."),
        "",
        "## 9. Development plan",
        "",
    ])
    milestones = plan.get("milestones")
    if isinstance(milestones, list) and milestones:
        for index, milestone in enumerate(milestones, start=1):
            if not isinstance(milestone, dict):
                continue
            refs = ", ".join(str(x) for x in milestone.get("requirement_refs", [])) or "No requirement references supplied"
            sections.extend([
                f"### {index}. {_value(milestone.get('name'), 'Unnamed milestone')}",
                "",
                _value(milestone.get("description")),
                "",
                f"- Requirement references: {refs}",
                "",
                "Tasks:",
                "",
            ])
            tasks = milestone.get("tasks")
            if isinstance(tasks, list) and tasks:
                for task in tasks:
                    if isinstance(task, dict):
                        task_refs = ", ".join(str(x) for x in task.get("requirement_refs", [])) or "No requirement references supplied"
                        sections.append(f"- {_value(task.get('description'))} (requirements: {task_refs})")
            else:
                sections.append("No tasks were recorded for this milestone.")
            sections.append("")
    else:
        sections.extend(["No development milestones have been generated yet.", ""])
    sections.extend([
        "## 10. Cross-artifact review",
        "",
        f"- Technical review status: {_value(review.get('overall_status'), 'Not reviewed yet')}",
        f"- Technical review summary: {_value(review.get('summary'), 'No technical review is available.')}",
        "",
        "## 11. Limitations",
        "",
        "This document is rendered from saved Specra artifacts. It does not claim that application code or deployment infrastructure has been created or executed.",
        "",
    ])
    return "\n".join(sections)


def _test_report(project: dict, artifacts: dict, title: str) -> str:
    req = _artifact(artifacts, "requirements")
    plan = _artifact(artifacts, "project_plan")
    review = _artifact(artifacts, "technical_review", "review")
    coverage = review.get("requirement_coverage")
    sections = [
        f"# Software Test Plan and Test Report: {title}",
        "",
        "> Generated from the engineering blueprint. This is a proposed test plan and design-review summary, not evidence that generated application code has been executed.",
        "",
        "## 1. Execution status",
        "",
        "**Status: NOT RUN — this workflow has not recorded test execution against generated application code.**",
        "",
        f"- Project ID: {_value(project.get('project_id'))}",
        f"- Blueprint status: {_value(project.get('status'))}",
        f"- Technical review status: {_value(review.get('overall_status'), 'Not reviewed yet')}",
        f"- Technical review summary: {_value(review.get('summary'), 'No review summary is available.')}",
        "",
        "## 2. Test objective and scope",
        "",
        _value(req.get("objective")),
        "",
        "The scenarios below are proposals derived from requirement coverage. Adapt them to the implemented application, test data, and selected stack before execution.",
        "",
        "## 3. Requirement-based test scenarios",
        "",
    ]
    if isinstance(coverage, list) and coverage:
        for index, item in enumerate(coverage, start=1):
            if not isinstance(item, dict):
                continue
            req_id = _value(item.get("requirement_id"), f"REQ-{index:03d}")
            sections.extend([
                f"### TC-{index:03d}: Validate {req_id}",
                "",
                f"- Requirement: {_value(item.get('requirement'))}",
                "- Proposed test: Exercise the implemented user workflow using valid input, then verify its expected outcome and persisted state.",
                "- Expected result: The documented behavior occurs without an unhandled error and the related application state is consistent.",
                "- Execution: NOT RUN",
                f"- Blueprint coverage — plan: {'Yes' if item.get('in_project_plan') else 'No'}; architecture: {'Yes' if item.get('in_architecture') else 'No'}; API: {'Yes' if item.get('in_api') else 'No'}",
                "",
            ])
    else:
        functional = req.get("functional_requirements")
        if isinstance(functional, list) and functional:
            for index, requirement in enumerate(functional, start=1):
                sections.extend([
                    f"### TC-{index:03d}",
                    "",
                    f"- Requirement: {requirement}",
                    "- Proposed test: Exercise the implemented user workflow and verify its stated outcome.",
                    "- Expected result: The requirement is satisfied and observable in the application.",
                    "- Execution: NOT RUN",
                    "",
                ])
        else:
            sections.extend(["No functional requirements are available for test-case drafting.", ""])
    sections.extend([
        "## 4. Integration and system test checklist",
        "",
        "- Verify that frontend requests reach the expected backend API.",
        "- Verify persistence and retrieval across a backend restart after durable storage is configured.",
        "- Verify invalid input and unavailable dependencies produce actionable errors.",
        "- Verify access control before using private project data or testing multiple accounts.",
        "- Verify external integrations with test credentials and sandbox environments where available.",
        "- Run the generated application's actual unit and integration test suite in an isolated environment before marking scenarios as passed.",
        "",
        "## 5. Technical review findings",
        "",
        "Unsupported additions:",
        _bullets(review.get("unsupported_additions"), "None were recorded by the technical reviewer."),
        "",
        "Architecture consistency issues:",
        _bullets(review.get("architecture_consistency_issues"), "None were recorded by the technical reviewer."),
        "",
        "Recommended actions:",
        _bullets(review.get("recommended_actions"), "No recommended actions were recorded."),
        "",
        "## 6. Test readiness",
        "",
        f"- Planned milestones: {len(plan.get('milestones', [])) if isinstance(plan.get('milestones'), list) else 0}",
        f"- Functional requirements: {len(req.get('functional_requirements', [])) if isinstance(req.get('functional_requirements'), list) else 0}",
        "- Actual test execution results: none supplied by the current Specra workflow",
        "- Exit recommendation: do not mark this report PASS until cases are executed and results/evidence are recorded.",
        "",
    ])
    return "\n".join(sections)


def render_project_document(document_type: str, project: dict, artifacts: dict) -> tuple[str, str]:
    normalized = re.sub(r"[^a-z-]", "", document_type.strip().lower())
    if normalized not in DOCUMENT_TYPES:
        raise ValueError(
            f"Unknown document type '{document_type}'. Choose one of: {', '.join(sorted(DOCUMENT_TYPES))}."
        )
    title = _title(project, artifacts)
    safe_title = re.sub(r"[^a-zA-Z0-9_-]+", "-", title).strip("-_").lower() or "specra-project"
    renderers = {"srs": _srs, "sdd": _sdd, "test-report": _test_report}
    return f"{safe_title}-{normalized}.md", renderers[normalized](project, artifacts, title)
